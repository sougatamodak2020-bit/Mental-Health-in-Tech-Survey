# -------------------------------------------------
# 2. Clean Age column (remove unrealistic values)
# Keep only ages between 18 and 75 (realistic working age range)
# -------------------------------------------------
print("\nAge statistics BEFORE cleaning:")
print(df_clean['Age'].describe())

