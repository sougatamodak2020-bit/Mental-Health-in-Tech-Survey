print("\nAge statistics AFTER cleaning:")
print(df_clean['Age'].describe())
print(f"Rows remaining after Age cleaning: {len(df_clean)}")

# -------------------------------------------------
# 3. Clean Gender column
# Map all free-text / misspelled entries into 3 clean categories:
# Male / Female / Other
# -------------------------------------------------
def clean_gender(gender):
    if pd.isna(gender):
        return 'Other'

    g = str(gender).strip().lower()

    # Male related terms
    male_keywords = ['male', 'm', 'male-ish', 'maile', 'cis male', 'mal',
                     'male (cis)', 'make', 'man', 'msle', 'mail', 'malr',
                     'cis man', 'male ', 'guy']

    # Female related terms
    female_keywords = ['female', 'f', 'woman', 'female ', 'cis female',
                       'femake', 'female (cis)', 'femail', 'trans-female',
                       'trans woman', 'female (trans)', 'woman']

    if g in male_keywords or ('male' in g and 'female' not in g and 'trans' not in g):
        return 'Male'
    elif g in female_keywords or ('female' in g) or g == 'f':
        return 'Female'
    else:
        return 'Other'

df_clean['Gender_clean'] = df_clean['Gender'].apply(clean_gender)

print("\nGender distribution AFTER cleaning:")
print(df_clean['Gender_clean'].value_counts())

# -------------------------------------------------
# 4. Handle missing values in self_employed
# -------------------------------------------------
# Most respondents are not self-employed. Filling with mode ('No')
df_clean['self_employed'] = df_clean['self_employed'].fillna('No')

# -------------------------------------------------
# 5. Handle missing values in work_interfere
# -------------------------------------------------
# Missing usually means the person did not report a mental health condition
# We create a clear category for analysis
df_clean['work_interfere'] = df_clean['work_interfere'].fillna('Not applicable')

# -------------------------------------------------
# 6. Create Age Groups (useful for visualization)
# -------------------------------------------------
bins = [17, 25, 35, 45, 55, 75]
labels = ['18-25', '26-35', '36-45', '46-55', '56+']
df_clean['Age_group'] = pd.cut(df_clean['Age'], bins=bins, labels=labels)

print("\nAge Group distribution:")
print(df_clean['Age_group'].value_counts().sort_index())

# -------------------------------------------------
# 7. Group less frequent countries into 'Other'
# Keep top 8 countries for cleaner geographic analysis
# -------------------------------------------------
top_countries = df_clean['Country'].value_counts().nlargest(8).index.tolist()
df_clean['Country_grouped'] = df_clean['Country'].apply(
    lambda x: x if x in top_countries else 'Other'
)

print("\nCountry (grouped) distribution:")
print(df_clean['Country_grouped'].value_counts())

# -------------------------------------------------
# 8. Drop columns that are not useful for quantitative EDA
# -------------------------------------------------
# - comments : mostly empty free text
# - Timestamp : not needed for current analysis
# - Original Gender : we now have Gender_clean
df_clean = df_clean.drop(columns=['comments', 'Timestamp', 'Gender'], errors='ignore')

# -------------------------------------------------
# Final check
# -------------------------------------------------
